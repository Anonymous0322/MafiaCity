export type Copy = (typeof copy)["uz"];

export function getCopy(language: Language): Copy {
  return copy[language] as Copy;
}

/** `{n}` interpolation without pulling in a template engine. */
export function interpolate(template: string, params: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in params ? String(params[key]) : match,
  );
}

export function roleLabel(role: GameRole | undefined, t: Copy): string {
  if (!role) return "";
  switch (role) {
    case "mafia":
      return t.mafia;
    case "doctor":
      return t.doctor;
    case "detective":
      return t.detective;
    case "citizen":
      return t.citizen;
  }
}
